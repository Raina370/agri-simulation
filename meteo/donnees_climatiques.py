def estimer_temperature_moyenne_cycle(departement_nom, date_plantation, cycle_jours):
    """Estime la température moyenne attendue sur le cycle, pour un département donné."""
    from datetime import timedelta
    donnees = DONNEES_CLIMATIQUES_PAR_DEPARTEMENT.get(departement_nom)
    if not donnees:
        return None

    total, nb_jours = 0, 0
    date_courante = date_plantation
    date_fin = date_plantation + timedelta(days=cycle_jours)
    while date_courante < date_fin:
        total += donnees["temperature"][date_courante.month]
        nb_jours += 1
        date_courante += timedelta(days=1)
    return round(total / nb_jours, 1)


def estimer_pluviometrie_cycle(departement_nom, date_plantation, cycle_jours):
    """Estime la pluviométrie cumulée attendue sur le cycle, pour un département donné."""
    from datetime import timedelta
    donnees = DONNEES_CLIMATIQUES_PAR_DEPARTEMENT.get(departement_nom)
    if not donnees:
        return None

    total = 0
    date_courante = date_plantation
    date_fin = date_plantation + timedelta(days=cycle_jours)
    while date_courante < date_fin:
        total += donnees["pluviometrie"][date_courante.month] / 30
        date_courante += timedelta(days=1)
    return round(total)